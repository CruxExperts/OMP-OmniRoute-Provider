import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import * as ts from "typescript";

const root = resolve(import.meta.dir, "..");
const json = (path: string) => JSON.parse(readFileSync(resolve(root, path), "utf8"));
const cell = (value: unknown): string => String(value).replaceAll("|", "\\|").replace(/[\r\n]/g, " ");
const linkPath = (path: string): string => {
  if (!/^docs\/[a-z0-9/.-]+\.md$/.test(path) || path.split("/").includes("..")) throw new Error(`Invalid documentation path: ${path}`);
  return path.slice(5);
};
const pkg = json("package.json");
const version = readFileSync(resolve(root, "VERSION"), "utf8").trim();
if (pkg.version !== version) throw new Error("package.json and VERSION differ; synchronize with version:set");
const marketplace = json(".omp-plugin/marketplace.json");
if (marketplace.version !== version) throw new Error("marketplace version differs from VERSION");
const inventory = json("contracts/operations.json");
const upstreams = json("provenance/upstreams.json");
const source = ts.createSourceFile("index.ts", readFileSync(resolve(root, "src/index.ts"), "utf8"), ts.ScriptTarget.Latest, true);
const commands = new Set<string>();
function visit(node: ts.Node): void {
  if (ts.isCallExpression(node) && ts.isPropertyAccessExpression(node.expression)
    && node.expression.name.text === "registerCommand" && node.arguments[0] && ts.isStringLiteral(node.arguments[0])) commands.add(node.arguments[0].text);
  ts.forEachChild(node, visit);
}
visit(source);
const declared = [...marketplace.commands].map((s: string) => s.replace(/^\//, "")).sort();
if (JSON.stringify([...commands].sort()) !== JSON.stringify(declared)) throw new Error("Registered commands and marketplace commands differ");
const byFamily = new Map<string, Record<string, number>>();
for (const operation of inventory.operations) {
  const family = String(operation.path ?? operation.operationId.split(" ")[1]).split("/").filter(Boolean).slice(0, 2).join("/");
  const counts = byFamily.get(family) ?? { invokable: 0, unqualified: 0, "non-invokable": 0 };
  if (!(operation.coverage.status in counts)) throw new Error("Unknown operation coverage status");
  counts[operation.coverage.status] = (counts[operation.coverage.status] ?? 0) + 1;
  byFamily.set(family, counts);
}
const lines = ["# Generated client reference", "", "<!-- Generated by scripts/generate-docs.ts. Edit the owning sources. -->", "", "## Version and compatibility", "", `Source version: **${cell(version)}**. This identifies checkout source, not an npm publication or a completed platform qualification.`, "", "| Component | Declared source | Meaning |", "| --- | --- | --- |", `| OMP host | ${cell(pkg.omp.compatibility.host)} | Declared compatible range |`, `| OMP host test matrix | ${cell(pkg.omp.compatibility.tested.join(", "))} | Requested test versions; require fresh release receipts |`];
for (const upstream of upstreams.upstreams) lines.push(`| ${cell(upstream.id)} | ${cell(upstream.release.tag)} (${cell(upstream.release.peeled_commit)}) | Pinned provenance; latest release must be rechecked |`);
lines.push("", "## Registered commands", "", "| Command |", "| --- |", ...[...commands].sort().map(command => `| \`/${cell(command)}\` |`), "", "## Operation inventory", "", "Qualified means the inventory marks an operation invokable. It does not establish live-account or eight-platform release acceptance. Unqualified operations remain blocked. Source-justified exceptions are listed in the contract with their evidence.", "", "| Route family | Qualified | Unqualified | Source exceptions |", "| --- | ---: | ---: | ---: |", ...[...byFamily.entries()].sort(([a], [b]) => a.localeCompare(b, "en")).map(([family, count]) => `| ${cell(family)} | ${count.invokable} | ${count.unqualified} | ${count["non-invokable"]} |`), "");
const index = Bun.YAML.parse(readFileSync(resolve(root, "docs/index.yaml"), "utf8")) as { root: string; documents: Array<{ id: string; path: string; title: string; category_label: string }> };
if (index.root !== "docs" || !Array.isArray(index.documents)) throw new Error("Invalid documentation index");
const indexLines = ["# Documentation", "", "<!-- Generated from docs/index.yaml by scripts/generate-docs.ts. -->", ""];
const ids = new Set<string>();
const paths = new Set<string>();
for (const category of [...new Set(index.documents.map(doc => doc.category_label))].sort()) {
  indexLines.push(`## ${cell(category)}`, "");
  for (const doc of index.documents.filter(doc => doc.category_label === category).sort((a, b) => a.title.localeCompare(b.title, "en"))) {
    if (ids.has(doc.id) || paths.has(doc.path)) throw new Error("Duplicate documentation index entry");
    ids.add(doc.id); paths.add(doc.path);
    const path = linkPath(doc.path);
    if (doc.path !== "docs/reference/generated.md") readFileSync(resolve(root, doc.path));
    indexLines.push(`- [${cell(doc.title).replaceAll("[", "\\[").replaceAll("]", "\\]")}](${path})`);
  }
  indexLines.push("");
}
for (const [path, content] of [["docs/reference/generated.md", lines.join("\n")], ["docs/INDEX.md", indexLines.join("\n")]]) {
  if (process.argv.includes("--check")) {
    if (readFileSync(resolve(root, path!), "utf8") !== content) throw new Error(`${path} is stale; run bun run scripts/generate-docs.ts`);
  } else writeFileSync(resolve(root, path!), content!);
}
